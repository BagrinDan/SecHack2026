const Ctx = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = localStorage.getItem('lang')
    return saved in dict ? saved : 'ru'
  })
  useEffect(() => {
    localStorage.setItem('lang', lang)
    document.documentElement.lang = lang
  }, [lang])

  // t('key', { n: 3 }) подставляет {n} в строку перевода.
  const t = useCallback(
    (key, vars) => (dict[lang][key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars && k in vars ? vars[k] : `{${k}}`)),
    [lang],
  )
  const locale = LOCALES[lang]
  const value = useMemo(() => ({ lang, setLang, t, locale }), [lang, t, locale])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)

export const fmtMdl = (n, locale) => `${Math.round(n ?? 0).toLocaleString(locale)} MDL`
export const fmtDwell = (s, t) => (s == null ? '—' : s >= 60 ? `${(s / 60).toFixed(1)} ${t('u_min')}` : `${Math.round(s)} ${t('u_s')}`)
